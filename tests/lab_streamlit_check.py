"""Exercise the self-contained tool iframe inside the real Streamlit app."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
from pypdf import PdfReader
OUT=Path('test-results/lab');OUT.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
 b=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox'])
 page=b.new_page(viewport={'width':1440,'height':1100},accept_downloads=True)
 errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto('http://127.0.0.1:8501');page.get_by_role('button',name='Ingresar al estudio →').first.click()
 page.get_by_role('tab',name='Herramientas creativas',exact=True).click()
 frame=page.frame_locator('iframe').nth(2)
 expect(frame.locator('#guide-title')).to_have_text('Cambiar tamaño')
 frame.locator('#guide-next').click();expect(frame.locator('#guide-count')).to_have_text('PASO 2 DE 3')
 frame.get_by_role('button',name='PDF extra',exact=True).click();frame.locator('#lab-tool').select_option('forms');frame.locator('#lab-sample').click()
 expect(frame.get_by_label('Nombre',exact=True)).to_be_enabled(timeout=30000);frame.get_by_label('Nombre',exact=True).fill('María del Perú');frame.locator('#lab-run').click();expect(frame.locator('.lab-download')).to_be_visible(timeout=30000)
 with page.expect_download() as event:frame.locator('.lab-download').click()
 assert PdfReader(event.value.path()).get_fields()['Nombre']['/V']=='María del Perú'
 # Palette editor accepts a real SVG previously generated by our vectorizer.
 frame.get_by_role('button',name='Colores SVG',exact=True).click()
 vectors=list(Path('test-results/vector-browser').glob('*.svg'))
 if vectors:frame.locator('#lab-file').set_input_files(str(vectors[0]))
 else:frame.locator('#lab-sample').click()
 expect(frame.locator('#lab-run')).to_be_enabled(timeout=30000);frame.locator('#lab-run').click();expect(frame.locator('.lab-download')).to_be_visible()
 frame.locator('#guide-title').scroll_into_view_if_needed();page.screenshot(path=str(OUT/'streamlit-desktop.png'))
 page.set_viewport_size({'width':390,'height':844});frame.locator('#guide-title').scroll_into_view_if_needed();assert frame.locator('html').evaluate('el=>el.scrollWidth<=innerWidth');page.screenshot(path=str(OUT/'streamlit-mobile.png'))
 assert not errors,errors
 b.close()
print('PASS: Streamlit guide, PDF form download with accents, existing vectorizer SVG roundtrip, mobile.')
