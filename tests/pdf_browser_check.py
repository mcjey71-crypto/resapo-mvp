"""Real local PDF operations; independent validation with pypdf, no mocked engine.
Run npm test first to create fixtures. Start server on PDF_TEST_URL (default port 8001).
"""
from pathlib import Path
import base64
import io
import os
import zipfile
from pypdf import PdfReader
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'test-results/pdf-browser'
OUT.mkdir(parents=True, exist_ok=True)
FIX = ROOT / 'test-results/pdf-fixtures'
BASE = os.getenv('PDF_TEST_URL', 'http://127.0.0.1:8001/pdf')


def downloaded(page, name):
    with page.expect_download() as event:
        page.locator('#pdf-download').click()
    target = OUT / name
    event.value.save_as(target)
    return target


def choose(page, tool, files):
    page.locator(f'[data-tool="{tool}"]').click()
    page.locator('#pdf-input').set_input_files([str(f) for f in files])
    expect(page.locator('#pdf-files .pdf-file')).to_have_count(len(files))
    expect(page.locator('#pdf-working')).to_be_hidden(timeout=30000)


def generate(page):
    page.locator('#pdf-run').click()
    expect(page.locator('#pdf-result')).to_be_visible(timeout=30000)
    expect(page.locator('#pdf-working')).to_be_hidden(timeout=30000)


def words(path):
    return [(p.extract_text() or '').strip() for p in PdfReader(path).pages]


with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/chromium', headless=True, args=['--no-sandbox'])
    context = browser.new_context(viewport={'width':1440,'height':1100})
    page = context.new_page()
    errors, network_writes = [], []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.on('request', lambda req: network_writes.append(req.url) if req.method in ['POST','PUT'] else None)
    page.goto(BASE)
    expect(page.locator('#pdf-sample')).to_be_enabled()
    page.screenshot(path=str(OUT/'desktop.png'), full_page=True)
    context.set_offline(True)
    # Real engine on the sample works without network or uploads.
    page.locator('#pdf-sample').click()
    expect(page.locator('#pdf-files .pdf-file')).to_have_count(2)
    generate(page)
    assert len(PdfReader(downloaded(page,'sample.pdf')).pages) == 6
    page.locator('#pdf-clear').click()
    choose(page,'merge',[FIX/'a.pdf',FIX/'b.pdf'])
    page.get_by_role('button',name='Bajar a.pdf',exact=True).click()
    generate(page)
    assert words(downloaded(page,'merged.pdf')) == ['B1','B2','A1','A2','A3']
    page.locator('#pdf-clear').click()
    choose(page,'extract',[FIX/'a.pdf'])
    page.locator('#pdf-ranges').fill('3,1')
    generate(page)
    assert words(downloaded(page,'extracted.pdf')) == ['A3','A1']
    page.locator('#pdf-ranges').fill('0')
    expect(page.locator('#pdf-result')).to_be_hidden()
    page.locator('#pdf-run').click()
    expect(page.locator('#pdf-message')).to_contain_text('entre 1 y 3')
    choose(page,'split',[FIX/'a.pdf'])
    page.locator('#pdf-ranges').fill('1-2;3')
    generate(page)
    with zipfile.ZipFile(downloaded(page,'split.zip')) as archive:
        assert archive.namelist() == ['parte-01.pdf','parte-02.pdf']
        assert words(io.BytesIO(archive.read('parte-01.pdf'))) == ['A1','A2']
        assert words(io.BytesIO(archive.read('parte-02.pdf'))) == ['A3']
    page.locator('#pdf-each-page').check()
    expect(page.locator('#pdf-ranges')).to_be_disabled()
    generate(page)
    expect(page.locator('#pdf-ranges')).to_be_disabled()
    with zipfile.ZipFile(downloaded(page,'each.zip')) as archive: assert len(archive.namelist()) == 3
    choose(page,'remove',[FIX/'a.pdf'])
    expect(page.locator('#pdf-ranges')).to_be_enabled()
    page.locator('#pdf-ranges').fill('2')
    generate(page)
    assert words(downloaded(page,'removed.pdf')) == ['A1','A3']
    page.locator('#pdf-ranges').fill('1-3')
    page.locator('#pdf-run').click()
    expect(page.locator('#pdf-message')).to_contain_text('al menos una')
    choose(page,'organize',[FIX/'a.pdf'])
    page.get_by_role('button',name='Mover página 3 antes',exact=True).click()
    page.get_by_role('button',name='Girar página 2',exact=True).click()
    page.get_by_role('checkbox',name='Seleccionar página 1',exact=True).check()
    page.locator('#pdf-delete-pages').click()
    generate(page)
    path=downloaded(page,'organized.pdf')
    assert words(path)==['A3','A2']
    assert [p.rotation for p in PdfReader(path).pages]==[0,180]
    page.locator('#pdf-reset-order').click()
    expect(page.locator('#pdf-pages .pdf-page-card')).to_have_count(3)
    # Real image files, including non-square images, generated by the browser.
    for extension,mime,width,height in [('png','image/png',80,40),('jpg','image/jpeg',40,80)]:
        data=page.evaluate('''([mime,w,h])=>{const c=document.createElement('canvas');c.width=w;c.height=h;const x=c.getContext('2d');x.fillStyle='#5c8321';x.fillRect(0,0,w,h);return c.toDataURL(mime).split(',')[1]}''',[mime,width,height])
        (OUT/f'image.{extension}').write_bytes(base64.b64decode(data))
    choose(page,'images',[OUT/'image.png',OUT/'image.jpg'])
    page.locator('#pdf-orientation').select_option('landscape')
    generate(page)
    reader=PdfReader(downloaded(page,'images.pdf'))
    assert len(reader.pages)==2
    assert all(abs(float(p.mediabox.width)-841.89)<.01 for p in reader.pages)
    assert all(any(x.get_object().get('/Subtype')=='/Image' for x in p['/Resources']['/XObject'].values()) for p in reader.pages)
    page.locator('#pdf-size').select_option('original')
    expect(page.locator('#pdf-orientation')).to_be_disabled()
    generate(page)
    expect(page.locator('#pdf-orientation')).to_be_disabled()
    reader=PdfReader(downloaded(page,'image-original.pdf'))
    assert tuple(float(x) for x in (reader.pages[0].mediabox.width,reader.pages[0].mediabox.height))==(108,78)
    page.locator('[data-tool="extract"]').click()
    page.locator('#pdf-input').set_input_files(str(ROOT/'tests/fixtures/encrypted.pdf'))
    expect(page.locator('#pdf-message')).to_contain_text('contraseña')
    expect(page.locator('#pdf-files .pdf-file')).to_have_count(0)
    page.locator('#pdf-input').set_input_files({'name':'broken.pdf','mimeType':'application/pdf','buffer':b'invalid'})
    expect(page.locator('#pdf-message')).to_contain_text('No pudimos leer')
    expect(page.locator('#pdf-files .pdf-file')).to_have_count(0)
    # Upload-looking names are treated as text, and failed additions keep current documents.
    page.locator('[data-tool="merge"]').click()
    payload={'name':'<img src=x onerror=alert(1)>.pdf','mimeType':'application/pdf','buffer':(FIX/'a.pdf').read_bytes()}
    page.locator('#pdf-input').set_input_files(payload)
    expect(page.locator('#pdf-files .pdf-file')).to_have_count(1)
    assert page.locator('#pdf-files img').count()==0
    page.locator('#pdf-input').set_input_files({'name':'broken.pdf','mimeType':'application/pdf','buffer':b'invalid'})
    expect(page.locator('#pdf-message')).to_contain_text('No pudimos leer')
    expect(page.locator('#pdf-files .pdf-file')).to_have_count(1)
    # Responsive layout with actual page controls, plus no writes to the network.
    page.locator('[data-tool="organize"]').click()
    page.locator('#pdf-input').set_input_files(str(FIX/'a.pdf'))
    expect(page.locator('#pdf-pages .pdf-page-card')).to_have_count(3)
    page.evaluate("document.querySelector('#pdf-run').click(); document.querySelector('#pdf-cancel').click();")
    expect(page.locator('#pdf-message')).to_contain_text('cancelada')
    expect(page.locator('#pdf-result')).to_be_hidden()
    generate(page)
    assert words(downloaded(page,'after-cancel.pdf')) == ['A1','A2','A3']
    page.set_viewport_size({'width':390,'height':844})
    assert not page.evaluate('document.documentElement.scrollWidth > innerWidth')
    page.screenshot(path=str(OUT/'mobile.png'),full_page=True)
    assert not errors,errors
    assert not network_writes,network_writes
    # Exercise the single-file build in an isolated offline document.
    # This managed browser blocks file:// navigation by administrator policy.
    portable=context.new_page()
    portable.set_content((ROOT/'docs/index.html').read_text())
    portable.locator('#pdf-sample').click()
    expect(portable.locator('#pdf-files .pdf-file')).to_have_count(2)
    generate(portable)
    assert len(PdfReader(downloaded(portable,'portable.pdf')).pages)==6
    browser.close()
print('PASS: six PDF tools, actual downloads, independent content/rotation/image checks, encrypted/corrupt inputs, mobile, no uploads and offline portable HTML.')
